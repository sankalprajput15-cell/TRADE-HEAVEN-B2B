export function isAutoGeneratedRfq(rfq?: Partial<RfqRequirement> | null): boolean {
  if (!rfq) return false;
  return Boolean(
    rfq.source === 'auto_generated' ||
      rfq.syncTag === 'market_sync' ||
      rfq.sync_tag === 'market_sync' ||
      rfq.marketDemandVerified === true ||
      String(rfq.id || '').startsWith('rfq-auto-') ||
      String(rfq.id || '').startsWith('rfq-mkt-') ||
      String(rfq.id || '').startsWith('G4W-BUY-')
  );
}

export function sortRfqsRealFirst(list: RfqRequirement[]): RfqRequirement[] {
  return [...(list || [])].sort((a, b) => {
    const aAuto = isAutoGeneratedRfq(a) ? 1 : 0;
    const bAuto = isAutoGeneratedRfq(b) ? 1 : 0;
    if (aAuto !== bAuto) return aAuto - bAuto;

    const aSeq = typeof (a as any).pageSequenceOrder === 'number' ? (a as any).pageSequenceOrder : null;
    const bSeq = typeof (b as any).pageSequenceOrder === 'number' ? (b as any).pageSequenceOrder : null;
    if (aSeq !== null && bSeq !== null) {
      return aSeq - bSeq;
    }
    if (aSeq !== null) return 1;
    if (bSeq !== null) return -1;

    return String(b.postedDate || b.id || '').localeCompare(String(a.postedDate || a.id || ''));
  });
}

export function sanitizeSearchKeyword(raw?: string | null): string {
  let clean = String(raw || '').trim();
  if (!clean) return '';
  for (let i = 0; i < 4; i++) {
    clean = clean
      .replace(/^(?:search|keyword|query|filter|rfq|find|sector|category)\s*:\s*/i, '')
      .replace(/^["'“”‘’`]+|["'“”‘’`]+$/g, '')
      .trim();
  }
  return clean.replace(/\s+/g, ' ');
}

export function matchesRfqKeywordClient(rfq: RfqRequirement, keyword: string): boolean {
  const q = sanitizeSearchKeyword(keyword).toLowerCase();
  if (!q) return true;
  const tokens = q.split(/\s+/).filter(Boolean);
  const rawSearchKw = String(rfq.searchKeyword || '');
  const primarySearchKw = rawSearchKw.includes('|')
    ? sanitizeSearchKeyword(rawSearchKw.split('|').pop() || '')
    : sanitizeSearchKeyword(rawSearchKw);
  const cleanTitle = sanitizeSearchKeyword(rfq.productName || rfq.title || '');
  const searchable = [
    cleanTitle,
    rfq.productName,
    rfq.title,
    rfq.category,
    rfq.detailedDescription,
    rfq.detailedRequirements,
    primarySearchKw,
    rfq.destinationPort,
    rfq.buyerCountry,
    rfq.preferredIncoterm,
    rfq.paymentTerms,
    rfq.id
  ]
    .filter(Boolean)
    .join(' ')
    .toLowerCase();

  return tokens.every(token => searchable.includes(token));
}

export function mergeRfqLists(baseList: RfqRequirement[], incomingList: RfqRequirement[]): RfqRequirement[] {
  const map = new Map<string, RfqRequirement>();
  (baseList || []).forEach(r => {
    if (r && r.id) map.set(r.id, r);
  });
  (incomingList || []).forEach(r => {
    if (r && r.id) {
      const existing = map.get(r.id);
      map.set(r.id, {
        ...existing,
        ...r,
        ...(typeof (existing as any)?.pageSequenceOrder === 'number' &&
        typeof (r as any)?.pageSequenceOrder !== 'number'
          ? { pageSequenceOrder: (existing as any).pageSequenceOrder }
          : {})
      });
    }
  });
  return Array.from(map.values());
}

/**
 * Automatically pre-warms & locally uploads verified product images (/assets/uploads/auto-*.webp)
 * for newly generated RFQs in the background without sending any email notifications.
 */
export function prewarmAndAutoSaveRfqImages(rfqs: RfqRequirement[]): void {
  if (!Array.isArray(rfqs) || rfqs.length === 0) return;

  rfqs.slice(0, 24).forEach((rfq, idx) => {
    const cleanTitle = String(rfq.productName || rfq.title || '').trim();
    if (cleanTitle.length < 3) return;

    const existingOverride =
      productImageManagerService.getProductImage(rfq.id) ||
      productImageManagerService.getProductImage(cleanTitle) ||
      productImageManagerService.resolveImageSrc({ productTitle: cleanTitle, category: rfq.category, productId: rfq.id });

    if (existingOverride && existingOverride.startsWith('/assets/uploads/')) {
      rfq.image = existingOverride;
      rfq.images = [existingOverride];
      productImageManagerService.registerAutoSavedImage({
        productId: rfq.id,
        productTitle: cleanTitle,
        url: existingOverride
      });
      return;
    }

    // Stagger background visual discovery + local upload so pages stay responsive
    setTimeout(() => {
      fetchVisualProductImages({
        productName: cleanTitle,
        productId: rfq.id,
        category: rfq.category,
        count: 15
      })
        .then(res => {
          if (res.success && Array.isArray(res.pool) && res.pool.length > 0) {
            const topUrl = res.pool[0]?.url;
            if (topUrl && !isGenericOrPlaceholderImageUrl(topUrl)) {
              if (topUrl.startsWith('/assets/uploads/')) {
                productImageManagerService.registerAutoSavedImage({
                  productId: rfq.id,
                  productTitle: cleanTitle,
                  url: topUrl
                });
              }
              void autoUploadDisplayedProductImage({
                imageUrl: topUrl,
                productId: rfq.id,
                productName: cleanTitle,
                category: rfq.category
              }).then(localUrl => {
                if (localUrl) {
                  productImageManagerService.registerAutoSavedImage({
                    productId: rfq.id,
                    productTitle: cleanTitle,
                    url: localUrl,
                    originalUrl: /^https?:\/\//i.test(topUrl) ? topUrl : undefined
                  });
                }
              });
            }
          }
        })
        .catch(() => {});
    }, idx * 80);
  });
}

export async function syncNewAutoRfqsToApiPhp(
  newlyGeneratedRfqs: RfqRequirement[],
  keyword: string,
  insightSummary: string
): Promise<void> {
  if (!Array.isArray(newlyGeneratedRfqs) || newlyGeneratedRfqs.length === 0) return;

  prewarmAndAutoSaveRfqImages(newlyGeneratedRfqs);

  // 1. Try fast batch persistence endpoint first (saves to server store & mirrors images with 0 emails)
  try {
    const batchRes = await fetch('/api/v1/rfqs/auto-batch-persist', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', Accept: 'application/json' },
      body: JSON.stringify({
        rfqs: newlyGeneratedRfqs,
        keyword,
        insightSummary
      })
    });
    const contentType = batchRes.headers.get('content-type') || '';
    if (batchRes.ok && contentType.includes('application/json')) {
      const parsed = await batchRes.json().catch(() => null);
      if (parsed && (parsed.success === true || parsed.status === 'success')) {
        return;
      }
    }
  } catch {
    // Fall through to individual api.php sync
  }

  await Promise.allSettled(
    newlyGeneratedRfqs.map(rfq =>
      apiClient.submitRfq({
        id: rfq.id,
        title: rfq.productName || rfq.title,
        product_name: rfq.productName || rfq.title,
        category: rfq.category,
        quantity: String(rfq.targetQuantity || 20),
        unit: rfq.quantityUnit || 'Metric Tons',
        order_frequency: rfq.orderFrequency || 'Monthly',
        targetPrice: String(rfq.targetPriceUsd || 0),
        incoterms: rfq.preferredIncoterm || 'CIF',
        destinationPort: rfq.destinationPort || 'Global Port',
        payment_terms: rfq.paymentTerms || 'CIF, LC / TT',
        specifications: rfq.detailedRequirements || rfq.detailedDescription || '',
        buyer_name: rfq.buyerName || 'International Procurement Officer',
        buyer_company: rfq.buyerCompany || 'Global Commodity Importers',
        buyer_country: rfq.buyerCountry || 'United Arab Emirates',
        buyer_email: rfq.buyerEmail || 'sourcing@globaltradeimport.com',
        buyer_phone: rfq.buyerPhone || '',
        buyer_address: rfq.buyerAddress || '',
        image_url: rfq.image || rfq.images?.[0] || '',
        images: rfq.images || (rfq.image ? [rfq.image] : []),
        source: 'auto_generated',
        sync_tag: 'market_sync',
        search_keyword: rfq.searchKeyword || keyword,
        market_insight: insightSummary || rfq.marketInsight || '',
        posted_label: rfq.postedLabel || 'Just now',
        status: 'OPEN'
      })
    )
  );
}

