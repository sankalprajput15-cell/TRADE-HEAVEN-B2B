export function isAutoGeneratedRfq(rfq?: Partial<RfqRequirement> | null): boolean {
  if (!rfq) return false;
  return Boolean(
    rfq.source === 'auto_generated' ||
      rfq.syncTag === 'market_sync' ||
      rfq.sync_tag === 'market_sync' ||
      rfq.marketDemandVerified === true ||
      String(rfq.id || '').startsWith('rfq-auto-') ||
      String(rfq.id || '').startsWith('rfq-mkt-') ||
      String(rfq.id || '').startsWith('G4W-BUY-')
  );
}

export function sortRfqsRealFirst(list: RfqRequirement[]): RfqRequirement[] {
  return [...(list || [])].sort((a, b) => {
    const aAuto = isAutoGeneratedRfq(a) ? 1 : 0;
    const bAuto = isAutoGeneratedRfq(b) ? 1 : 0;
    if (aAuto !== bAuto) return aAuto - bAuto;

    const aSeq = typeof (a as any).pageSequenceOrder === 'number' ? (a as any).pageSequenceOrder : null;
    const bSeq = typeof (b as any).pageSequenceOrder === 'number' ? (b as any).pageSequenceOrder : null;
    if (aSeq !== null && bSeq !== null) {
      return aSeq - bSeq;
    }
    if (aSeq !== null) return 1;
    if (bSeq !== null) return -1;

    return String(b.postedDate || b.id || '').localeCompare(String(a.postedDate || a.id || ''));
  });
}

export function matchesRfqKeywordClient(rfq: RfqRequirement, keyword: string): boolean {
  const q = String(keyword || '').toLowerCase().trim();
  if (!q) return true;
  const tokens = q.split(/\s+/).filter(Boolean);
  const searchable = [
    rfq.productName,
    rfq.title,
    rfq.category,
    rfq.detailedDescription,
    rfq.detailedRequirements,
    rfq.searchKeyword,
    rfq.destinationPort,
    rfq.buyerCountry,
    rfq.preferredIncoterm,
    rfq.paymentTerms,
    rfq.id
  ]
    .filter(Boolean)
    .join(' ')
    .toLowerCase();

  return tokens.every(token => searchable.includes(token));
}

export function mergeRfqLists(baseList: RfqRequirement[], incomingList: RfqRequirement[]): RfqRequirement[] {
  const map = new Map<string, RfqRequirement>();
  (baseList || []).forEach(r => {
    if (r && r.id) map.set(r.id, r);
  });
  (incomingList || []).forEach(r => {
    if (r && r.id) {
      const existing = map.get(r.id);
      map.set(r.id, {
        ...existing,
        ...r,
        ...(typeof (existing as any)?.pageSequenceOrder === 'number' &&
        typeof (r as any)?.pageSequenceOrder !== 'number'
          ? { pageSequenceOrder: (existing as any).pageSequenceOrder }
          : {})
      });
    }
  });
  return Array.from(map.values());
}

/**
 * Automatically pre-warms & locally uploads verified product images (/assets/uploads/auto-*.webp)
 * for newly generated RFQs in the background without sending any email notifications.
 */
export function prewarmAndAutoSaveRfqImages(rfqs: RfqRequirement[]): void {
  if (!Array.isArray(rfqs) || rfqs.length === 0) return;

  rfqs.slice(0, 24).forEach((rfq, idx) => {
    const cleanTitle = String(rfq.productName || rfq.title || '').trim();
    if (cleanTitle.length < 3) return;

    const existingOverride =
      productImageManagerService.getProductImage(rfq.id) ||
      productImageManagerService.getProductImage(cleanTitle) ||
      productImageManagerService.resolveImageSrc({ productTitle: cleanTitle, category: rfq.category, productId: rfq.id });

    if (existingOverride && existingOverride.startsWith('/assets/uploads/')) {
      rfq.image = existingOverride;
      rfq.images = [existingOverride];
      productImageManagerService.registerAutoSavedImage({
        productId: rfq.id,
        productTitle: cleanTitle,
        url: existingOverride
      });
      return;
    }

    // Stagger background visual discovery + local upload so pages stay responsive
    setTimeout(() => {
      fetchVisualProductImages({
        productName: cleanTitle,
        productId: rfq.id,
        category: rfq.category,
        count: 15
      })
        .then(res => {
          if (res.success && Array.isArray(res.pool) && res.pool.length > 0) {
            const topUrl = res.pool[0]?.url;
            if (topUrl && !isGenericOrPlaceholderImageUrl(topUrl)) {
              if (topUrl.startsWith('/assets/uploads/')) {
                productImageManagerService.registerAutoSavedImage({
                  productId: rfq.id,
                  productTitle: cleanTitle,
                  url: topUrl
                });
              }
              void autoUploadDisplayedProductImage({
                imageUrl: topUrl,
                productId: rfq.id,
                productName: cleanTitle,
                category: rfq.category
              }).then(localUrl => {
                if (localUrl) {
                  productImageManagerService.registerAutoSavedImage({
                    productId: rfq.id,
                    productTitle: cleanTitle,
                    url: localUrl,
                    originalUrl: /^https?:\/\//i.test(topUrl) ? topUrl : undefined
                  });
                }
              });
            }
          }
        })
        .catch(() => {});
    }, idx * 80);
  });
}

export async function syncNewAutoRfqsToApiPhp(
  newlyGeneratedRfqs: RfqRequirement[],
  keyword: string,
  insightSummary: string
): Promise<void> {
  if (!Array.isArray(newlyGeneratedRfqs) || newlyGeneratedRfqs.length === 0) return;

  prewarmAndAutoSaveRfqImages(newlyGeneratedRfqs);

  // 1. Try fast batch persistence endpoint first (saves to server store & mirrors images with 0 emails)
  try {
    const batchRes = await fetch('/api/v1/rfqs/auto-batch-persist', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        rfqs: newlyGeneratedRfqs,
        keyword,
        insightSummary
      })
    });
    if (batchRes.ok) {
      return;
    }
  } catch {
    // Fall through to individual api.php sync
  }

  await Promise.allSettled(
    newlyGeneratedRfqs.map(rfq =>
      apiClient.submitRfq({
        id: rfq.id,
        title: rfq.productName || rfq.title,
        product_name: rfq.productName || rfq.title,
        category: rfq.category,
        quantity: String(rfq.targetQuantity || 20),
        unit: rfq.quantityUnit || 'Metric Tons',
        order_frequency: rfq.orderFrequency || 'Monthly',
        targetPrice: String(rfq.targetPriceUsd || 0),
        incoterms: rfq.preferredIncoterm || 'CIF',
        destinationPort: rfq.destinationPort || 'Global Port',
        payment_terms: rfq.paymentTerms || 'CIF, LC / TT',
        specifications: rfq.detailedRequirements || rfq.detailedDescription || '',
        buyer_name: rfq.buyerName || 'International Procurement Officer',
        buyer_company: rfq.buyerCompany || 'Global Commodity Importers',
        buyer_country: rfq.buyerCountry || 'United Arab Emirates',
        buyer_email: rfq.buyerEmail || 'sourcing@globaltradeimport.com',
        buyer_phone: rfq.buyerPhone || '',
        buyer_address: rfq.buyerAddress || '',
        image_url: rfq.image || rfq.images?.[0] || '',
        images: rfq.images || (rfq.image ? [rfq.image] : []),
        source: 'auto_generated',
        sync_tag: 'market_sync',
        search_keyword: rfq.searchKeyword || keyword,
        market_insight: insightSummary || rfq.marketInsight || '',
        posted_label: rfq.postedLabel || 'Just now',
        status: 'OPEN'
      })
    )
  );
}

let globalPageSequenceCounter = 10000;

/**
 * Generates and persists a fresh batch of contextual RFQs whenever pagination advances to the next page,
 * binding already-saved local product images and pre-warming/auto-uploading any uncached product images.
 */
export function generateAndPersistNextPageRfqs(
  options: ContextualPageRfqOptions & { currentUser?: AuthUser | null }
): RfqRequirement[] {
  const startSeq = globalPageSequenceCounter;
  globalPageSequenceCounter += (options.count || 36) + 10;

  const rawBatch = generateContextualPageRfqs({
    ...options,
    startSequence: startSeq
  });

  // Immediately attach any already-saved local /assets/uploads/ images
  rawBatch.forEach(rfq => {
    const savedImg =
      productImageManagerService.getProductImage(rfq.id) ||
      productImageManagerService.getProductImage(rfq.productName) ||
      productImageManagerService.resolveImageSrc({ productTitle: rfq.productName, category: rfq.category, productId: rfq.id });
    if (savedImg && savedImg.startsWith('/assets/uploads/')) {
      rfq.image = savedImg;
      rfq.images = [savedImg];
    }
  });

  // Persist to backend & pre-warm/auto-upload local product images in background (zero emails)
  void syncNewAutoRfqsToApiPhp(
    rawBatch,
    options.searchTerm || 'global_trade_pagination',
    ''
  ).catch(() => {});

  return rawBatch.map(r => {
    const gated = securityService.gateRfqRequirement(r, options.currentUser || null);
    (gated as any).pageSequenceOrder = (r as any).pageSequenceOrder;
    return gated;
  });
}

const sessionDiscoveredSearchTerms = new Set<string>();

export async function checkAndDiscoverRfqsForKeyword(params: {
  keyword: string;
  searchResults?: string[];
  currentRfqs: RfqRequirement[];
  currentUser?: AuthUser | null;
}): Promise<{
  rfqs: RfqRequirement[];
  insight: MarketDemandInsight | null;
  triggeredAi: boolean;
  notice?: string | null;
}> {
  const trimmed = String(params.keyword || '').trim();
  const currentUser = params.currentUser || null;

  if (!trimmed || trimmed.length < 2) {
    return { rfqs: params.currentRfqs, insight: null, triggeredAi: false };
  }

  const normalizedQuery = trimmed.toLowerCase();
  const cleanSearchResults = Array.isArray(params.searchResults)
    ? Array.from(
        new Set(
          params.searchResults
            .map(s => String(s || '').trim().replace(/\s+/g, ' '))
            .filter(s => s.length >= 2 && s.toLowerCase() !== normalizedQuery)
        )
      ).slice(0, 10)
    : [];

  const getUncoveredSearchResults = (rfqPool: RfqRequirement[]): string[] =>
    cleanSearchResults.filter(item => {
      const normItem = item.toLowerCase();
      if (sessionDiscoveredSearchTerms.has(normItem)) return false;
      const hasAutoOrMatch = rfqPool.some(
        r => isAutoGeneratedRfq(r) && matchesRfqKeywordClient(r, item)
      );
      return !hasAutoOrMatch;
    });

  // 1. Check current state first
  const localMatches = params.currentRfqs.filter(r => matchesRfqKeywordClient(r, trimmed));
  const localUncovered = getUncoveredSearchResults(params.currentRfqs);
  if (localMatches.length >= 3 && localUncovered.length === 0) {
    const matchedAutoInsight = localMatches.find(r => r.marketInsight)?.marketInsight;
    const cachedInsight = await apiClient.getMarketInsight(trimmed);
    const insightObj: MarketDemandInsight | null =
      cachedInsight ||
      (matchedAutoInsight
        ? {
            keyword: trimmed,
            summary: matchedAutoInsight,
            generatedAt: new Date().toISOString(),
            fromCache: true
          }
        : null);
    return { rfqs: params.currentRfqs, insight: insightObj, triggeredAi: false };
  }

  // 2. Database-First Check via api.php / backend
  let mergedRfqs = [...params.currentRfqs];
  try {
    const dbRfqs = await api.getRfqs(undefined, currentUser);
    if (Array.isArray(dbRfqs) && dbRfqs.length > 0) {
      mergedRfqs = mergeRfqLists(mergedRfqs, dbRfqs);
    }
  } catch {
    // Non-blocking fallback
  }

  const dbMatches = mergedRfqs.filter(r => matchesRfqKeywordClient(r, trimmed));
  const dbUncovered = getUncoveredSearchResults(mergedRfqs);
  if (dbMatches.length >= 3 && dbUncovered.length === 0) {
    const matchedAutoInsight = dbMatches.find(r => r.marketInsight)?.marketInsight;
    const cachedInsight = await apiClient.getMarketInsight(trimmed);
    const insightObj: MarketDemandInsight | null =
      cachedInsight ||
      (matchedAutoInsight
        ? {
            keyword: trimmed,
            summary: matchedAutoInsight,
            generatedAt: new Date().toISOString(),
            fromCache: true
          }
        : null);
    return { rfqs: mergedRfqs, insight: insightObj, triggeredAi: false };
  }

  // 3. Generate auto-RFQs for primary query (< 3 matches) AND all uncovered search results
  dbUncovered.forEach(item => sessionDiscoveredSearchTerms.add(item.toLowerCase()));
  const discoverRes = await apiClient.discoverMarketDemandRfqs(trimmed, dbUncovered);
  if (discoverRes.rfqs && discoverRes.rfqs.length > 0) {
    const rawReturned = discoverRes.rfqs as RfqRequirement[];
    const newlyGenerated =
      Array.isArray(discoverRes.newlyGeneratedRfqs) && discoverRes.newlyGeneratedRfqs.length > 0
        ? (discoverRes.newlyGeneratedRfqs as RfqRequirement[])
        : (!discoverRes.fromCache ? rawReturned.filter(isAutoGeneratedRfq) : []);

    if (newlyGenerated.length > 0) {
      await syncNewAutoRfqsToApiPhp(
        newlyGenerated,
        trimmed,
        discoverRes.insight?.summary || ''
      ).catch(() => {});
    }

    const gatedReturned = rawReturned.map(r => securityService.gateRfqRequirement(r, currentUser));
    mergedRfqs = mergeRfqLists(mergedRfqs, gatedReturned);

    if (typeof window !== 'undefined') {
      window.dispatchEvent(new CustomEvent('tradeheaven_rfq_created'));
    }

    return {
      rfqs: mergedRfqs,
      insight: discoverRes.insight || null,
      triggeredAi: !discoverRes.fromCache,
      notice: discoverRes.success ? null : (discoverRes.message || null)
    };
  }

  return {
    rfqs: mergedRfqs,
    insight: discoverRes.insight || null,
    triggeredAi: false,
    notice: discoverRes.message || null
  };
}
