import { AuthUser, MarketDemandInsight, RfqRequirement } from '../types';
import { apiClient } from './apiClient';
import { api } from './apiService';
import { securityService } from './securityService';

export function isAutoGeneratedRfq(rfq?: Partial<RfqRequirement> | null): boolean {
  if (!rfq) return false;
  return Boolean(
    rfq.source === 'auto_generated' ||
      rfq.syncTag === 'market_sync' ||
      rfq.sync_tag === 'market_sync' ||
      rfq.marketDemandVerified === true
  );
}

export function sortRfqsRealFirst(list: RfqRequirement[]): RfqRequirement[] {
  return [...(list || [])].sort((a, b) => {
    const aAuto = isAutoGeneratedRfq(a) ? 1 : 0;
    const bAuto = isAutoGeneratedRfq(b) ? 1 : 0;
    if (aAuto !== bAuto) return aAuto - bAuto;
    return String(b.postedDate || b.id || '').localeCompare(String(a.postedDate || a.id || ''));
  });
}

export function matchesRfqKeywordClient(rfq: RfqRequirement, keyword: string): boolean {
  const q = String(keyword || '').toLowerCase().trim();
  if (!q) return true;
  const tokens = q.split(/\s+/).filter(Boolean);
  const searchable = [
    rfq.productName,
    rfq.title,
    rfq.category,
    rfq.detailedDescription,
    rfq.detailedRequirements,
    rfq.searchKeyword,
    rfq.destinationPort,
    rfq.buyerCountry,
    rfq.preferredIncoterm,
    rfq.paymentTerms,
    rfq.id
  ]
    .filter(Boolean)
    .join(' ')
    .toLowerCase();

  return tokens.every(token => searchable.includes(token));
}

export function mergeRfqLists(baseList: RfqRequirement[], incomingList: RfqRequirement[]): RfqRequirement[] {
  const map = new Map<string, RfqRequirement>();
  (baseList || []).forEach(r => {
    if (r && r.id) map.set(r.id, r);
  });
  (incomingList || []).forEach(r => {
    if (r && r.id) map.set(r.id, r);
  });
  return Array.from(map.values());
}

export async function syncNewAutoRfqsToApiPhp(
  newlyGeneratedRfqs: RfqRequirement[],
  keyword: string,
  insightSummary: string
): Promise<void> {
  if (!Array.isArray(newlyGeneratedRfqs) || newlyGeneratedRfqs.length === 0) return;

  await Promise.allSettled(
    newlyGeneratedRfqs.map(rfq =>
      apiClient.submitRfq({
        id: rfq.id,
        title: rfq.productName || rfq.title,
        product_name: rfq.productName || rfq.title,
        category: rfq.category,
        quantity: String(rfq.targetQuantity || 20),
        unit: rfq.quantityUnit || 'Metric Tons',
        order_frequency: rfq.orderFrequency || 'Monthly',
        targetPrice: String(rfq.targetPriceUsd || 0),
        incoterms: rfq.preferredIncoterm || 'CIF',
        destinationPort: rfq.destinationPort || 'Global Port',
        payment_terms: rfq.paymentTerms || 'CIF, LC / TT',
        specifications: rfq.detailedRequirements || rfq.detailedDescription || '',
        buyer_name: rfq.buyerName || 'International Procurement Officer',
        buyer_company: rfq.buyerCompany || 'Global Commodity Importers',
        buyer_country: rfq.buyerCountry || 'United Arab Emirates',
        buyer_email: rfq.buyerEmail || 'sourcing@globaltradeimport.com',
        buyer_phone: rfq.buyerPhone || '',
        buyer_address: rfq.buyerAddress || '',
        source: 'auto_generated',
        sync_tag: 'market_sync',
        search_keyword: keyword,
        market_insight: insightSummary || rfq.marketInsight || '',
        posted_label: rfq.postedLabel || 'Just now',
        status: 'OPEN'
      })
    )
  );
}

export async function checkAndDiscoverRfqsForKeyword(params: {
  keyword: string;
  currentRfqs: RfqRequirement[];
  currentUser?: AuthUser | null;
}): Promise<{
  rfqs: RfqRequirement[];
  insight: MarketDemandInsight | null;
  triggeredAi: boolean;
  notice?: string | null;
}> {
  const trimmed = String(params.keyword || '').trim();
  const currentUser = params.currentUser || null;

  if (!trimmed || trimmed.length < 2) {
    return { rfqs: params.currentRfqs, insight: null, triggeredAi: false };
  }

  // 1. Check current state first
  const localMatches = params.currentRfqs.filter(r => matchesRfqKeywordClient(r, trimmed));
  if (localMatches.length >= 3) {
    const matchedAutoInsight = localMatches.find(r => r.marketInsight)?.marketInsight;
    const cachedInsight = await apiClient.getMarketInsight(trimmed);
    const insightObj: MarketDemandInsight | null =
      cachedInsight ||
      (matchedAutoInsight
        ? {
            keyword: trimmed,
            summary: matchedAutoInsight,
            generatedAt: new Date().toISOString(),
            fromCache: true
          }
        : null);
    return { rfqs: params.currentRfqs, insight: insightObj, triggeredAi: false };
  }

  // 2. Database-First Check via api.php / backend
  let mergedRfqs = [...params.currentRfqs];
  try {
    const dbRfqs = await api.getRfqs(undefined, currentUser);
    if (Array.isArray(dbRfqs) && dbRfqs.length > 0) {
      mergedRfqs = mergeRfqLists(mergedRfqs, dbRfqs);
    }
  } catch {
    // Non-blocking fallback
  }

  const dbMatches = mergedRfqs.filter(r => matchesRfqKeywordClient(r, trimmed));
  if (dbMatches.length >= 3) {
    const matchedAutoInsight = dbMatches.find(r => r.marketInsight)?.marketInsight;
    const cachedInsight = await apiClient.getMarketInsight(trimmed);
    const insightObj: MarketDemandInsight | null =
      cachedInsight ||
      (matchedAutoInsight
        ? {
            keyword: trimmed,
            summary: matchedAutoInsight,
            generatedAt: new Date().toISOString(),
            fromCache: true
          }
        : null);
    return { rfqs: mergedRfqs, insight: insightObj, triggeredAi: false };
  }

  // 3. < 3 matches in DB -> Call Gemini Google Search Grounding endpoint
  const discoverRes = await apiClient.discoverMarketDemandRfqs(trimmed);
  if (discoverRes.rfqs && discoverRes.rfqs.length > 0) {
    const rawReturned = discoverRes.rfqs as RfqRequirement[];
    const newlyGenerated =
      Array.isArray(discoverRes.newlyGeneratedRfqs) && discoverRes.newlyGeneratedRfqs.length > 0
        ? (discoverRes.newlyGeneratedRfqs as RfqRequirement[])
        : (!discoverRes.fromCache ? rawReturned.filter(isAutoGeneratedRfq) : []);

    if (newlyGenerated.length > 0) {
      await syncNewAutoRfqsToApiPhp(
        newlyGenerated,
        trimmed,
        discoverRes.insight?.summary || ''
      ).catch(() => {});
    }

    const gatedReturned = rawReturned.map(r => securityService.gateRfqRequirement(r, currentUser));
    mergedRfqs = mergeRfqLists(mergedRfqs, gatedReturned);

    if (typeof window !== 'undefined') {
      window.dispatchEvent(new CustomEvent('tradeheaven_rfq_created'));
    }

    return {
      rfqs: mergedRfqs,
      insight: discoverRes.insight || null,
      triggeredAi: !discoverRes.fromCache,
      notice: discoverRes.success ? null : (discoverRes.message || null)
    };
  }

  return {
    rfqs: mergedRfqs,
    insight: discoverRes.insight || null,
    triggeredAi: false,
    notice: discoverRes.message || null
  };
}
